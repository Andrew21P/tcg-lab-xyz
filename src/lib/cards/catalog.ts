type CardInput = {
  setCode: string;
  setName: string;
  number: string;
  name: string;
  regulationMark: string;
  supertype: Supertype;
  subtypes: string[];
  hp?: number;
  types?: EnergyType[];
  evolvesFrom?: string;
  attacks?: CardAttack[];
  abilities?: CardAbility[];
  weaknesses?: { type: EnergyType; value: string }[];
  resistances?: { type: EnergyType; value: string }[];
  retreat?: number;
  rules?: string[];
  rarity?: string;
  roles?: RoleTag[];
  whenGood?: string;
  whenBrick?: string;
  scripted?: boolean;
};

function card(input: CardInput): TcgCard {
  const setId = SET_IMAGE_IDS[input.setCode] ?? input.setCode.toLowerCase();
  const id = `${input.setCode.toLowerCase()}-${input.number}`;
  return {
    id,
    name: input.name,
    setCode: input.setCode,
    setName: input.setName,
    number: input.number,
    regulationMark: input.regulationMark,
    supertype: input.supertype,
    subtypes: input.subtypes,
    hp: input.hp,
    types: input.types,
    evolvesFrom: input.evolvesFrom,
    attacks: input.attacks,
    abilities: input.abilities,
    weaknesses: input.weaknesses,
    resistances: input.resistances,
    retreat: input.retreat,
    rules: input.rules,
    rarity: input.rarity,
    imageSmall: `https://images.pokemontcg.io/${setId}/${String(parseInt(input.number, 10) || input.number)}.png`,
    imageLarge: `https://images.pokemontcg.io/${setId}/${String(parseInt(input.number, 10) || input.number)}_hires.png`,
    ptcgoCode: input.setCode,
    legalities: { ...LEGAL },
    roles: input.roles,
    whenGood: input.whenGood,
    whenBrick: input.whenBrick,
    scripted: input.scripted,
  };
}

function basicEnergy(
  setCode: string,
  setName: string,
  number: string,
  type: EnergyType,
  mark: string,
): TcgCard {
  return card({
    setCode,
    setName,
    number,
    name: `${type} Energy`,
    regulationMark: mark,
    supertype: "Energy",
    subtypes: ["Basic"],
    types: [type],
    rules: [`Provides 1 ${type} Energy.`],
    rarity: "Common",
    roles: ["engine"],
    whenGood: "Fuels attackers of this type.",
    whenBrick: "Dead if you are off-type or flooded.",
    scripted: true,
  });
}

function item(
  setCode: string,
  setName: string,
  number: string,
  name: string,
  mark: string,
  rules: string,
  extra: Partial<CardInput> = {},
): TcgCard {
  return card({
    setCode,
    setName,
    number,
    name,
    regulationMark: mark,
    supertype: "Trainer",
    subtypes: ["Item"],
    rules: [rules],
    rarity: "Common",
    ...extra,
  });
}

