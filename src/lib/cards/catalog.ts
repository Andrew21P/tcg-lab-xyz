function stadium(
  setCode: string,
  setName: string,
  number: string,
  name: string,
  mark: string,
  rules: string,
  extra: Partial<CardInput> = {},
): TcgCard {
  return card({
    setCode,
    setName,
    number,
    name,
    regulationMark: mark,
    supertype: "Trainer",
    subtypes: ["Stadium"],
    rules: [rules],
    rarity: "Uncommon",
    ...extra,
  });
}

function aceSpec(
  setCode: string,
  setName: string,
  number: string,
  name: string,
  mark: string,
  rules: string,
  subtype: "Item" | "Supporter" | "Stadium" | "Tool" = "Item",
  extra: Partial<CardInput> = {},
): TcgCard {
  return card({
    setCode,
    setName,
    number,
    name,
    regulationMark: mark,
    supertype: "Trainer",
    subtypes: [subtype, "ACE SPEC"],
    rules: ["You can't have more than 1 ACE SPEC card in your deck.", rules],
    rarity: "ACE SPEC Rare",
    roles: ["ace-spec", ...(extra.roles ?? [])],
    scripted: true,
    ...extra,
  });
}

